/** Preview/export before an explicit idle-session command; no model-triggered compaction. */
import { randomBytes } from 'node:crypto'
import { mkdir, open, readdir, realpath } from 'node:fs/promises'
import { isAbsolute, join } from 'node:path'
import { ToolkitToolError, toolkitJsonOutput, toolkitObject, toolkitThrowIfCancelled, type ToolkitToolDefinition } from './host-tools.ts'

export interface ContextRescueSnapshot {
  sessionId: string
  /** Adapter-owned content/routing revision; exclude command/approval audit-only events. */
  revision: string
  idle: boolean
  events: readonly unknown[]
  surfaceNodes: readonly number[]
  estimatedTokens?: number
  summaryTarget?: { provider: 'workbuddy' | 'workbuddy-ai'; model: string }
  servingAccount?: string
}
export interface ContextRescueDependencies {
  enabled: () => boolean | Promise<boolean>
  exportDirectory: string
  /** Use the host query observation API, not deprecated synchronous Session event reads. */
  readSnapshot: (agent: unknown, signal: AbortSignal) => Promise<ContextRescueSnapshot>
  /** Recheck expected revision synchronously at entry, then invoke host compactNow (owns idle lock). */
  compact: (agent: unknown, signal: AbortSignal, expected: ContextRescueSnapshot) => Promise<unknown>
  now?: () => number
}
export interface ContextRescuePreview {
  id: string
  revision: string
  sessionId: string
  exportFile: string
  exportedBytes: number
  surfaceItems: number
  estimatedTokens?: number
  summaryTarget?: { provider: 'workbuddy' | 'workbuddy-ai'; model: string }
  servingAccount?: string
  summaryText: 'Generated by the host only after explicit apply; exact retained text cannot be previewed.'
}
interface PendingPreview { preview: ContextRescuePreview; snapshot: ContextRescueSnapshot; expiresAt: number }
const MAX_EXPORT_BYTES = 4_194_304
const MAX_EXPORTS = 20
const PREVIEW_TTL_MS = 15 * 60_000
const EXPORT_PREFIX = 'workbuddy-rescue-'

export class ContextRescueService {
  private readonly previews = new Map<string, PendingPreview>()
  private readonly lifecycle = new AbortController()
  private stopped = false
  private previewBusy = false
  constructor(private readonly deps: ContextRescueDependencies) {}

  private async admitted(signal: AbortSignal): Promise<void> {
    if (this.stopped) throw new ToolkitToolError('disposed')
    toolkitThrowIfCancelled(signal)
    if (!await this.deps.enabled()) throw new ToolkitToolError('feature-disabled')
    toolkitThrowIfCancelled(signal)
    if (this.stopped) throw new ToolkitToolError('disposed')
  }

  async preview(agent: unknown, signal: AbortSignal): Promise<ContextRescuePreview> {
    if (this.previewBusy) throw new ToolkitToolError('rescue-preview-busy')
    this.previewBusy = true
    try { return await this.exportPreview(agent, AbortSignal.any([signal, this.lifecycle.signal])) }
    finally { this.previewBusy = false }
  }

  private async exportPreview(agent: unknown, signal: AbortSignal): Promise<ContextRescuePreview> {
    await this.admitted(signal)
    const sourceSnapshot = await this.deps.readSnapshot(agent, signal)
    // Own revision/identity values even if a caller reuses its snapshot container.
    const snapshot = { ...sourceSnapshot }
    await this.admitted(signal)
    if (typeof snapshot.sessionId !== 'string' || snapshot.sessionId.length === 0 || snapshot.sessionId.length > 256
      || typeof snapshot.revision !== 'string' || snapshot.revision.length === 0 || snapshot.revision.length > 512
      || !Array.isArray(snapshot.events) || snapshot.events.length > 20_000 || !Array.isArray(snapshot.surfaceNodes)
      || snapshot.surfaceNodes.some(seq => !Number.isSafeInteger(seq) || seq < 0)) throw new ToolkitToolError('rescue-snapshot-invalid')
    let text: string
    if (snapshot.summaryTarget !== undefined && (!['workbuddy', 'workbuddy-ai'].includes(snapshot.summaryTarget.provider) || typeof snapshot.summaryTarget.model !== 'string' || !/^[a-zA-Z0-9][a-zA-Z0-9._:/-]{0,255}$/u.test(snapshot.summaryTarget.model))) throw new ToolkitToolError('rescue-snapshot-invalid')
    if (snapshot.servingAccount !== undefined && !/^(cn|global)-[a-f0-9]{32}$/u.test(snapshot.servingAccount)) throw new ToolkitToolError('rescue-snapshot-invalid')
    try { text = JSON.stringify({ version: 1, sessionId: snapshot.sessionId, revision: snapshot.revision, events: snapshot.events, surfaceNodes: snapshot.surfaceNodes, ...(snapshot.summaryTarget === undefined ? {} : { summaryTarget: snapshot.summaryTarget }), ...(snapshot.servingAccount === undefined ? {} : { servingAccount: snapshot.servingAccount }) }) }
    catch { throw new ToolkitToolError('rescue-snapshot-invalid') }
    const bytes = Buffer.byteLength(text)
    if (bytes > MAX_EXPORT_BYTES) throw new ToolkitToolError('rescue-export-limit')
    const id = randomBytes(16).toString('hex')
    const file = `${EXPORT_PREFIX}${id}.json`
    try {
      if (!isAbsolute(this.deps.exportDirectory)) throw new Error('invalid directory')
      await mkdir(this.deps.exportDirectory, { recursive: true, mode: 0o700 })
      const directory = await realpath(this.deps.exportDirectory)
      // Original exports are recovery material. Stop growing rather than deleting them.
      if ((await readdir(directory)).filter(name => name.startsWith(EXPORT_PREFIX) && name.endsWith('.json')).length >= MAX_EXPORTS) throw new ToolkitToolError('rescue-export-limit')
      const handle = await open(join(directory, file), 'wx', 0o600)
      try { await handle.writeFile(text, 'utf8'); await handle.sync() } finally { await handle.close() }
    } catch (error) { throw error instanceof ToolkitToolError ? error : new ToolkitToolError('rescue-export-failed') }
    await this.admitted(signal)
    const preview: ContextRescuePreview = {
      id, revision: snapshot.revision, sessionId: snapshot.sessionId, exportFile: file, exportedBytes: bytes, surfaceItems: snapshot.surfaceNodes.length,
      ...(typeof snapshot.estimatedTokens === 'number' && Number.isFinite(snapshot.estimatedTokens) && snapshot.estimatedTokens >= 0 ? { estimatedTokens: snapshot.estimatedTokens } : {}),
      ...(snapshot.summaryTarget === undefined ? {} : { summaryTarget: { ...snapshot.summaryTarget } }),
      ...(snapshot.servingAccount === undefined ? {} : { servingAccount: snapshot.servingAccount }),
      summaryText: 'Generated by the host only after explicit apply; exact retained text cannot be previewed.',
    }
    const now = (this.deps.now ?? Date.now)()
    for (const [key, record] of this.previews) if (record.expiresAt <= now) this.previews.delete(key)
    if (this.previews.size >= MAX_EXPORTS) throw new ToolkitToolError('rescue-preview-limit')
    this.previews.set(id, { preview, snapshot, expiresAt: now + PREVIEW_TTL_MS })
    return { ...preview }
  }

  /** Called only by the explicitly invoked human command, never from a model tool. */
  async apply(agent: unknown, id: string, revision: string, signal: AbortSignal): Promise<{ status: 'applied' | 'unchanged' }> {
    signal = AbortSignal.any([signal, this.lifecycle.signal])
    await this.admitted(signal)
    const pending = this.previews.get(id)
    if (pending === undefined || pending.expiresAt <= (this.deps.now ?? Date.now)()) { this.previews.delete(id); throw new ToolkitToolError('rescue-preview-unavailable') }
    if (revision !== pending.preview.revision) throw new ToolkitToolError('rescue-preview-changed')
    const current = await this.deps.readSnapshot(agent, signal)
    await this.admitted(signal)
    if (!current.idle) throw new ToolkitToolError('rescue-session-busy')
    if (current.sessionId !== pending.snapshot.sessionId || current.revision !== pending.snapshot.revision) throw new ToolkitToolError('rescue-preview-changed')
    // Consume before mutation so concurrent commands, uncertain host failures and retries cannot duplicate it.
    if (this.previews.get(id) !== pending) throw new ToolkitToolError('rescue-preview-unavailable')
    this.previews.delete(id)
    let result: unknown
    try { result = await this.deps.compact(agent, signal, current) }
    catch { toolkitThrowIfCancelled(signal); throw new ToolkitToolError('rescue-apply-failed-inspect-session') }
    return { status: result === null ? 'unchanged' : 'applied' }
  }

  dispose(): void { this.stopped = true; this.previews.clear(); this.lifecycle.abort() }
}

export function createContextRescueTools(deps: { service: ContextRescueService }): ToolkitToolDefinition[] {
  return [{
    name: 'workbuddy_context_preview',
    description: 'Export the current session locally and preview context-rescue scope. Does not compact or resend requests. Apply only through the explicit human /workbuddy-rescue apply command while idle.',
    parameters: { type: 'object', properties: {}, additionalProperties: false }, output: toolkitJsonOutput(),
    execute: async (args, execution) => { toolkitObject(args, []); return await deps.service.preview(execution.agent, execution.signal) },
  }]
}

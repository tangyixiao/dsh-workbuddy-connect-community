import { mkdirSync, mkdtempSync, rmSync, writeFileSync, readFileSync } from 'node:fs'
import { join, resolve } from 'node:path'
import { afterEach, describe, expect, it } from 'vitest'
import { MediaTaskStore } from '../src/media-task-store.ts'
import { createMediaTools, WorkBuddyMediaService } from '../src/media-tools.ts'
import { WorkBuddyMediaClient } from '../src/media-client.ts'
import { workbuddySavedAccountId } from '../src/account-store.ts'

const paths: string[] = []
afterEach(() => { for (const path of paths.splice(0)) rmSync(path, { recursive: true, force: true }) })
function location(): string {
  mkdirSync(resolve('work/all-features-20261113'), { recursive: true })
  const dir = mkdtempSync(join(resolve('work/all-features-20261113'), 'media-test-'))
  paths.push(dir)
  return join(dir, 'tasks.json')
}
const credential = { accessToken: 'secret', refreshToken: '', expiresAtMs: 1, domain: '', uid: 'uid', source: 'desktop' as const }
const scope = { region: 'cn' as const, account: workbuddySavedAccountId('cn', credential), revision: 'revision-7' }
describe('durable media admission', () => {
  it('retains unknown submission before sending and refuses the same operation after restart', async () => {
    const path = location()
    const first = await new MediaTaskStore(path).prepare(scope, 'host-call-1', 'video')
    expect(first.fresh).toBe(true)
    expect(first.task.status).toBe('unknown')
    const restarted = new MediaTaskStore(path)
    expect((await restarted.prepare(scope, 'host-call-1', 'video')).fresh).toBe(false)
    expect(await restarted.get({ ...scope, account: `cn-${'b'.repeat(32)}` }, first.task.id)).toBeUndefined()
    expect(await restarted.get({ ...scope, region: 'global' }, first.task.id)).toBeUndefined()
  })
  it('denies malformed stored state rather than losing the unknown-before-send guard', async () => {
    const path = location()
    writeFileSync(path, '{invalid')
    await expect(new MediaTaskStore(path).prepare(scope, 'host-call-1', 'video')).rejects.toMatchObject({ code: 'media-state-unavailable' })
  })
  it('saves generated bytes only to its own output path and never stores base64 in the task document', async () => {
    const path = location()
    const store = new MediaTaskStore(path)
    const { task } = await store.prepare(scope, 'host-call-2', 'image')
    const result = await store.record(scope, task.id, { status: 'completed', files: [{ base64: 'aW1hZ2U=' }] })
    expect(result.files[0]?.localPath).toContain(join('workbuddy-media', task.id, '0.png'))
    expect(readFileSync(result.files[0]!.localPath!, 'utf8')).toBe('image')
    expect(readFileSync(path, 'utf8')).not.toContain('aW1hZ2U=')
  })
  it('requires enabled capability and fresh per-action approval, and never replays an unknown submission', async () => {
    let enabled = false
    let submissions = 0
    let approvals = 0
    const tools = createMediaTools({
      tasks: new MediaTaskStore(location()), client: new WorkBuddyMediaClient({ fetch: async () => { submissions++; throw new Error('token/path private error') } }),
      scope: async () => scope, enabled: async () => enabled,
      resolveAccess: async () => ({ credential: { accessToken: 'secret', refreshToken: '', expiresAtMs: 1, domain: '', uid: 'uid', source: 'desktop' }, model: { id: 'hunyuan-image-v3.0', tags: ['text-to-image'] } }),
      approval: { request: async () => { approvals++; return 'allowed-once' } },
    })
    const image = tools.find(t => t.name === 'workbuddy_image')!
    const execution = { agent: { session: { id: 'fixture-session' } }, signal: new AbortController().signal, callId: 'host-call-1' }
    await expect(image.execute({ mode: 'text', prompt: 'clouds' }, execution)).rejects.toMatchObject({ code: 'media-disabled' })
    expect(approvals).toBe(0)
    enabled = true
    const first = await image.execute({ mode: 'text', prompt: 'clouds' }, execution)
    expect(first).toMatchObject({ status: 'unknown', files: [] })
    expect(await image.execute({ mode: 'text', prompt: 'clouds' }, execution)).toEqual(first)
    expect(submissions).toBe(1)
  })
  it('does not submit when the selected durable scope changes while approval is open', async () => {
    let current = scope
    let submissions = 0
    const tools = createMediaTools({ tasks: new MediaTaskStore(location()), client: new WorkBuddyMediaClient({ fetch: async () => { submissions++; throw new Error() } }), scope: async () => current, enabled: async () => true,
      resolveAccess: async () => ({ credential, model: { id: 'hunyuan-image-v3.0', tags: ['text-to-image'] } }), approval: { request: async () => { current = { ...scope, revision: 'changed' }; return 'allowed-once' } } })
    await expect(tools[0]!.execute({ mode: 'text', prompt: 'x' }, { agent: { session: { id: 'fixture-session' } }, signal: new AbortController().signal, callId: 'call' })).rejects.toMatchObject({ code: 'media-account-changed' })
    expect(submissions).toBe(0)
  })
  it('queries only a stored account-bound video task once without polling or another generation', async () => {
    const store = new MediaTaskStore(location())
    const admitted = await store.prepare(scope, 'video-call', 'video')
    await store.record(scope, admitted.task.id, { upstreamTaskId: 'upstream-1', status: 'pending', files: [] })
    const requests: string[] = []
    const tools = createMediaTools({ tasks: store, client: new WorkBuddyMediaClient({ fetch: async url => { requests.push(String(url)); return Response.json({ code: 0, data: { status: 'running' } }) } }),
      scope: async () => scope, enabled: async () => true, resolveAccess: async () => ({ credential }) })
    expect(await tools[2]!.execute({ taskId: admitted.task.id }, { agent: { session: { id: 'fixture-session' } }, signal: new AbortController().signal })).toMatchObject({ status: 'pending', upstreamTaskId: 'upstream-1' })
    expect(requests).toEqual(['https://www.workbuddy.cn/v2/videos/tasks'])
  })
  it('asks approval for the concrete declared model with a scrubbed prompt and no durable admission on denial', async () => {
    let reason = ''
    const store = new MediaTaskStore(location())
    const tools = createMediaTools({ tasks: store, client: new WorkBuddyMediaClient({ fetch: async () => { throw new Error('Unexpected fixture transport') } }), scope: async () => scope, enabled: async () => true,
      resolveAccess: async () => ({ credential, model: { id: 'hunyuan-image-v3.0', tags: ['text-to-image'] } }),
      approval: { request: async request => { reason = request.reason; return 'rejected' } } })
    await expect(tools[0]!.execute({ mode: 'text', prompt: 'clouds C:/Users/private/file.png Bearer private-provider-token' }, { agent: { session: { id: 'fixture-session' } }, signal: new AbortController().signal, callId: 'reviewable-call' })).rejects.toMatchObject({ code: 'approval-rejected' })
    expect(reason).toContain('model hunyuan-image-v3.0; image/text; 0 image inputs; prompt')
    expect(reason).not.toContain('C:/Users')
    expect(reason).not.toContain('private-provider-token')
    expect(await store.list(scope)).toEqual([])
  })
  it('rejects a credential for a sibling account even when region and selected revision look valid', async () => {
    let approved = false
    const tools = createMediaTools({ tasks: new MediaTaskStore(location()), client: new WorkBuddyMediaClient({ fetch: async () => { throw new Error('Unexpected fixture transport') } }), scope: async () => scope, enabled: async () => true,
      resolveAccess: async () => ({ credential: { ...credential, uid: 'sibling' }, model: { id: 'hunyuan-image-v3.0', tags: ['text-to-image'] } }), approval: { request: async () => { approved = true; return 'allowed-once' } } })
    await expect(tools[0]!.execute({ mode: 'text', prompt: 'x' }, { agent: { session: { id: 'fixture-session' } }, signal: new AbortController().signal, callId: 'call' })).rejects.toMatchObject({ code: 'media-account-changed' })
    expect(approved).toBe(false)
  })
  it('cancels an in-flight request on disable and retains unknown without automatically resubmitting', async () => {
    let started!: () => void
    const began = new Promise<void>(resolve => { started = resolve })
    let requests = 0
    const options = { tasks: new MediaTaskStore(location()), client: new WorkBuddyMediaClient({ fetch: async () => { requests++; started(); return new Promise<Response>(() => {}) } }), scope: async () => scope, enabled: async () => true,
      resolveAccess: async () => ({ credential, model: { id: 'hunyuan-image-v3.0', tags: ['text-to-image'] } }), approval: { request: async () => 'allowed-once' as const } }
    const service = new WorkBuddyMediaService(options)
    const execution = { agent: { session: { id: 'fixture-session' } }, signal: new AbortController().signal, callId: 'cancelled-call' }
    const pending = service.submit('image', { mode: 'text', prompt: 'x' }, execution)
    await began
    service.cancel('image')
    expect(await pending).toMatchObject({ status: 'unknown' })
    expect(await service.submit('image', { mode: 'text', prompt: 'x' }, execution)).toMatchObject({ status: 'unknown' })
    expect(requests).toBe(1)
    service.dispose()
  })
  it('namespaces same call IDs by real host session and rejects a changed request in the same logical call', async () => {
    let submissions = 0
    const path = location()
    const options = { tasks: new MediaTaskStore(path), client: new WorkBuddyMediaClient({ fetch: async () => { submissions++; return Response.json({ code: 0, data: { data: [{ url: 'https://media.example/image.png' }] } }) } }), scope: async () => scope, enabled: async () => true,
      resolveAccess: async () => ({ credential, model: { id: 'hunyuan-image-v3.0', tags: ['text-to-image'] } }), approval: { request: async () => 'allowed-once' as const } }
    const service = new WorkBuddyMediaService(options)
    const firstExecution = { agent: { session: { id: 'session-one' } }, signal: new AbortController().signal, callId: 'call-1' }
    const secondExecution = { ...firstExecution, agent: { session: { id: 'session-two' } } }
    const first = await service.submit('image', { mode: 'text', prompt: 'one' }, firstExecution)
    const second = await service.submit('image', { mode: 'text', prompt: 'two' }, secondExecution)
    expect(second.id).not.toBe(first.id)
    expect(submissions).toBe(2)
    const restarted = new WorkBuddyMediaService({ ...options, tasks: new MediaTaskStore(path) })
    expect(await restarted.submit('image', { mode: 'text', prompt: 'one' }, firstExecution)).toEqual(first)
    await expect(restarted.submit('image', { mode: 'text', prompt: 'changed' }, firstExecution)).rejects.toMatchObject({ code: 'media-operation-changed' })
    expect(submissions).toBe(2)
  })
  it('requires a real host session before approval instead of accepting a model supplied identifier', async () => {
    let approved = false
    const tools = createMediaTools({ tasks: new MediaTaskStore(location()), client: new WorkBuddyMediaClient({ fetch: async () => { throw new Error('Unexpected fixture transport') } }), scope: async () => scope, enabled: async () => true,
      resolveAccess: async () => ({ credential, model: { id: 'hunyuan-image-v3.0', tags: ['text-to-image'] } }), approval: { request: async () => { approved = true; return 'allowed-once' } } })
    await expect(tools[0]!.execute({ mode: 'text', prompt: 'x' }, { agent: {}, signal: new AbortController().signal, callId: 'call' })).rejects.toMatchObject({ code: 'media-session-unavailable' })
    expect(approved).toBe(false)
  })
})
